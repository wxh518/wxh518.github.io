import Ajv from 'ajv'
import addFormats from 'ajv-formats'
import standaloneCode from 'ajv/dist/standalone/index.js'
import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import homepage from '../content/schemas/homepage.schema.json'
import posts from '../content/schemas/posts.schema.json'

// Worker 禁止动态生成代码：构建时编译 Schema，浏览器与服务端复用同一套校验。
const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true, esm: true } })
addFormats(ajv)
ajv.addSchema(homepage, 'homepage')
ajv.addSchema(posts, 'posts')
const code = standaloneCode(ajv, { homepage: 'homepage', posts: 'posts' })
await mkdir('src/generated', { recursive: true })
await build({ stdin: { contents: code, resolveDir: process.cwd(), loader: 'js' }, bundle: true, platform: 'browser', format: 'esm', outfile: 'src/generated/validators.js', minify: true, supported: { 'template-literal': false }, banner: { js: '// Generated by npm run generate:validators. Do not edit directly.' } })
await writeFile('src/generated/validators.d.ts', `import type { ValidateFunction } from 'ajv'\nexport const homepage: ValidateFunction\nexport const posts: ValidateFunction\n`)
console.log('Generated static content validators.')
